import { readFile } from 'node:fs/promises'
import { expect, test, type Page } from '@playwright/test'

/** The brand where it leaves the site: downloaded files, Python error messages and the served HTML. */

const OLD_BRAND = /trace[ _-]?table[ _-]?studio|study hub/i

const traceTable = (page: Page) => page.getByRole('table', { name: 'Trace table' })

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('tts:welcomed', '1'))
})

async function openTracePage(page: Page) {
  await page.goto('/trace-table')
  await expect(traceTable(page)).toBeVisible({ timeout: 80_000 })
  await expect(page.getByRole('status').filter({ hasText: /^Python ready$/ })).toBeVisible()
}

async function download(page: Page, button: string): Promise<string> {
  const [file] = await Promise.all([page.waitForEvent('download'), page.getByRole('dialog').getByRole('button', { name: button }).click()])
  return readFile(await file.path(), 'utf8')
}

test('JSON and LaTeX downloads name CS Practice Lab as their generator', async ({ page }) => {
  await openTracePage(page)
  await page.getByRole('button', { name: 'Export' }).click()

  const json = await download(page, 'Download .json')
  expect((JSON.parse(json) as { generator: string }).generator).toBe('CS Practice Lab')

  const tex = await download(page, 'Download .tex')
  expect(tex.split('\n')[0]).toBe('% Trace table: generated by CS Practice Lab')
  expect(tex).not.toMatch(OLD_BRAND)
})

test('a blocked import is explained under the CS Practice Lab name', async ({ page }) => {
  await openTracePage(page)
  await page.locator('.cm-content').first().fill('import js')
  await page.keyboard.press('Control+Enter')
  await expect(page.getByText("Importing 'js' is not available in CS Practice Lab").first()).toBeVisible()
})

for (const path of ['/', '/trace-table', '/truth-tables', '/number-systems', '/sorting-visualizer', '/about', '/privacy', '/accessibility']) {
  test(`${path}: the served HTML uses only the current brand`, async ({ request }) => {
    const html = await (await request.get(path)).text()
    expect(html).toContain('CS Practice Lab')
    expect(html).not.toMatch(OLD_BRAND)
  })
}
